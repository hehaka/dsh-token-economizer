#!/usr/bin/env node
// Wrap plugin/dsh/client/src/*.cjs in DSH's browser module envelope -> plugin/dsh/client.js.
// No bundler: the client is plain CommonJS, and the browser shell supplies react and the DSH
// packages through the factory's `require` (ADR 0003). Output is deterministic.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export function buildClient({ srcDir = join(ROOT, 'client', 'src'), id } = {}) {
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const moduleId = id ?? pkg.name;
  const files = readdirSync(srcDir).filter((f) => f.endsWith('.cjs')).sort();
  if (!files.includes('index.cjs')) throw new Error('client/src/index.cjs is missing');
  const defs = files.map((f) => `__defs[${JSON.stringify(`./${f}`)}] = function (module, exports, require) {\n${readFileSync(join(srcDir, f), 'utf8')}\n};`).join('\n');
  return `/* ${pkg.name} ${pkg.version} — generated by client/build.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(moduleId)},
  factory: (require) => {
    const __defs = {};
    const __cache = {};
    function __req(name) {
      if (!name.startsWith('./')) return require(name);
      if (!Object.hasOwn(__defs, name)) throw new Error(${JSON.stringify(`${moduleId}: unknown module `)} + name);
      if (!Object.hasOwn(__cache, name)) {
        const module = { exports: {} };
        __cache[name] = module;
        __defs[name].call(module.exports, module, module.exports, __req);
      }
      return __cache[name].exports;
    }
${defs}
    return __req('./index.cjs');
  },
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(ROOT, 'client.js');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, buildClient());
  console.log(`client bundle: ${out}`);
}
